'use client';

import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { toast } from '@/components/ui/Toast/toast';
import { currentUserId, useSession } from '@/lib/auth/useSession';
import { toUserMessage } from '@/lib/errors/messages';
import { reportUnexpected } from '@/lib/errors/report';
import { queryKeys } from '@/lib/query/keys';
import type { CatalogEntry, GearCategory, GearItem } from '@/lib/recipes/gear';
import { createClient } from '@/lib/supabase/client';

const CATALOG_COLUMNS = 'id, category, brand, model, name';
const ITEM_COLUMNS =
  'id, category, catalog_id, custom_name, nickname, notes, is_default, catalog:gear_catalog(id, brand, model, name)';

const DAY_MS = 24 * 60 * 60 * 1000;

/** `name` is generated by the database as "brand model"; fall back to that if it's missing. */
const catalogName = (row: { brand: string; model: string; name: string | null }): string =>
  row.name ?? `${row.brand} ${row.model}`;

/**
 * The whole active gear catalogue (about 100 rows), fetched once and filtered on the device
 * (query key `['gear-catalog']`, fresh for 24 hours).
 */
export function useGearCatalog() {
  return useQuery({
    queryKey: queryKeys.gearCatalog(),
    staleTime: DAY_MS,
    gcTime: 2 * DAY_MS,
    queryFn: async (): Promise<CatalogEntry[]> => {
      const { data, error } = await createClient()
        .from('gear_catalog')
        .select(CATALOG_COLUMNS)
        .eq('is_active', true)
        .order('brand')
        .order('model');
      if (error) throw error;
      return data.map((row) => ({ ...row, name: catalogName(row) }));
    },
  });
}

/** My gear items with their catalogue row joined in (query key `['gear']`). */
export function useGear() {
  const { user } = useSession();
  return useQuery({
    queryKey: queryKeys.gear(),
    enabled: Boolean(user),
    queryFn: async (): Promise<GearItem[]> => {
      const { data, error } = await createClient()
        .from('gear_items')
        .select(ITEM_COLUMNS)
        .order('created_at');
      if (error) throw error;
      return data.map((row) => ({
        ...row,
        catalog: row.catalog ? { id: row.catalog.id, name: catalogName(row.catalog) } : null,
      }));
    },
  });
}

/** What a person can set on a gear item. Exactly one of `catalog_id` and `custom_name`. */
export type GearInput = {
  category: GearCategory;
  catalog_id: string | null;
  custom_name: string | null;
  nickname: string | null;
  notes: string | null;
};

/**
 * Renaming or deleting gear also changes `profiles.favourite_gear` (a database trigger keeps the
 * entries in step), so the profile is refreshed along with the gear list.
 */
function useRefreshGear() {
  const queryClient = useQueryClient();
  return () =>
    Promise.all([
      queryClient.invalidateQueries({ queryKey: queryKeys.gear() }),
      queryClient.invalidateQueries({ queryKey: queryKeys.profileMe() }),
    ]);
}

function onGearError(error: unknown, retry?: () => void) {
  reportUnexpected(error);
  toast.error(toUserMessage(error), retry ? { onRetry: retry } : undefined);
}

/** Cache change for the default switch: one default per category, shown straight away. */
function withDefault(items: GearItem[], id: string, isDefault: boolean): GearItem[] {
  const target = items.find((i) => i.id === id);
  if (!target) return items;
  return items.map((i) => {
    if (i.id === id) return { ...i, is_default: isDefault };
    if (isDefault && i.category === target.category) return { ...i, is_default: false };
    return i;
  });
}

/**
 * Turns a gear item's default on or off. On: `gear_set_default` clears the old default and sets
 * this one in one transaction. Off: an ordinary update. The list changes first and rolls back if
 * the save fails.
 */
export function useSetDefaultGear() {
  const queryClient = useQueryClient();
  const refresh = useRefreshGear();
  return useMutation({
    mutationFn: async ({ id, isDefault }: { id: string; isDefault: boolean }) => {
      const supabase = createClient();
      if (isDefault) {
        const { error } = await supabase.rpc('gear_set_default', { p_item_id: id });
        if (error) throw error;
        return;
      }
      const { error } = await supabase
        .from('gear_items')
        .update({ is_default: false })
        .eq('id', id);
      if (error) throw error;
    },
    onMutate: async ({ id, isDefault }) => {
      await queryClient.cancelQueries({ queryKey: queryKeys.gear() });
      const previous = queryClient.getQueryData<GearItem[]>(queryKeys.gear());
      if (previous)
        queryClient.setQueryData(queryKeys.gear(), withDefault(previous, id, isDefault));
      return { previous };
    },
    onError: (error, _vars, context) => {
      if (context?.previous) queryClient.setQueryData(queryKeys.gear(), context.previous);
      onGearError(error);
    },
    onSettled: refresh,
  });
}

/** Adds a gear item (optionally as the default for its category). Returns the new item's id. */
export function useAddGear() {
  const refresh = useRefreshGear();
  return useMutation({
    mutationFn: async (input: GearInput & { is_default?: boolean }): Promise<string> => {
      const { is_default, ...fields } = input;
      const supabase = createClient();
      const userId = await currentUserId();
      const { data, error } = await supabase
        .from('gear_items')
        .insert({ ...fields, user_id: userId })
        .select('id')
        .single();
      if (error) throw error;
      if (is_default) {
        const { error: defaultError } = await supabase.rpc('gear_set_default', {
          p_item_id: data.id,
        });
        if (defaultError) throw defaultError;
      }
      return data.id;
    },
    onError: (error) => onGearError(error),
    onSettled: refresh,
  });
}

/**
 * Saves changes to a gear item and, when asked, sets whether it is the default. The flag is
 * cleared in the same update (so a category change can't clash with the category's existing
 * default), then `gear_set_default` sets it again when it should be on.
 */
export function useUpdateGear() {
  const refresh = useRefreshGear();
  return useMutation({
    mutationFn: async ({
      id,
      is_default,
      ...fields
    }: GearInput & { id: string; is_default?: boolean }): Promise<void> => {
      const supabase = createClient();
      const { error } = await supabase
        .from('gear_items')
        .update(is_default === undefined ? fields : { ...fields, is_default: false })
        .eq('id', id);
      if (error) throw error;
      if (is_default) {
        const { error: defaultError } = await supabase.rpc('gear_set_default', { p_item_id: id });
        if (defaultError) throw defaultError;
      }
    },
    onError: (error) => onGearError(error),
    onSettled: refresh,
  });
}

/** Deletes a gear item. Recipes keep the name they saved; favourites drop it (database trigger). */
export function useDeleteGear() {
  const refresh = useRefreshGear();
  return useMutation({
    mutationFn: async (id: string) => {
      const { error } = await createClient().from('gear_items').delete().eq('id', id);
      if (error) throw error;
    },
    onError: (error) => onGearError(error),
    onSettled: refresh,
  });
}
