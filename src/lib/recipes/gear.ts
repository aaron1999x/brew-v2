import type { Database } from '@/types/database';

export type GearCategory = Database['public']['Enums']['gear_category'];

/** Order of the My gear groups and of the gear pickers on the Settings screen. */
export const GEAR_CATEGORIES = [
  'brewer',
  'filter',
  'grinder',
  'kettle',
  'scale',
  'water',
  'other',
] as const satisfies readonly GearCategory[];

/** The categories a recipe records (everything except "other"). */
export const RECIPE_GEAR_CATEGORIES = [
  'brewer',
  'filter',
  'grinder',
  'kettle',
  'scale',
  'water',
] as const satisfies readonly GearCategory[];

export type RecipeGearCategory = (typeof RECIPE_GEAR_CATEGORIES)[number];

export const GEAR_CATEGORY_LABELS: Record<GearCategory, string> = {
  brewer: 'Brewer',
  filter: 'Filter',
  grinder: 'Grinder',
  kettle: 'Kettle',
  scale: 'Scale',
  water: 'Water',
  other: 'Other',
};

/** A catalogue row (only the fields this module needs). */
export type CatalogEntry = {
  id: string;
  category: GearCategory;
  brand: string;
  model: string;
  /** `brand || ' ' || model`, generated by the database. */
  name: string;
};

/** A gear item of mine, with its catalogue row joined in when it has one. */
export type GearItem = {
  id: string;
  category: GearCategory;
  catalog_id: string | null;
  custom_name: string | null;
  nickname: string | null;
  notes: string | null;
  is_default: boolean;
  catalog?: Pick<CatalogEntry, 'id' | 'name'> | null;
};

/** What a saved version keeps for one gear category. Never contains a nickname. */
export type GearSnapshotEntry = {
  item_id?: string;
  catalog_id?: string;
  name: string;
};

export type GearSnapshot = Partial<Record<RecipeGearCategory, GearSnapshotEntry>>;

/** The real name of a gear item: the catalogue name, else the custom name. Never the nickname. */
export function gearRealName(item: Pick<GearItem, 'custom_name' | 'catalog'>): string {
  return item.catalog?.name ?? item.custom_name ?? '';
}

/** What My gear and the pickers show: the nickname, else the catalogue name, else the custom name. */
export function gearDisplayName(
  item: Pick<GearItem, 'nickname' | 'custom_name' | 'catalog'>,
): string {
  const nickname = item.nickname?.trim();
  return nickname ? nickname : gearRealName(item);
}

/** One of the ways a recipe's gear picker can be filled. */
export type GearChoice =
  | { kind: 'item'; item: GearItem }
  | { kind: 'catalog'; catalog: Pick<CatalogEntry, 'id' | 'name'> }
  | { kind: 'text'; text: string }
  /** An entry already saved on a version, kept exactly as it was. */
  | { kind: 'snapshot'; entry: GearSnapshotEntry };

export type GearSelection = Partial<Record<RecipeGearCategory, GearChoice | null>>;

/** The snapshot entry for a choice. Items store their real name, never their nickname. */
export function choiceToEntry(choice: GearChoice): GearSnapshotEntry | null {
  switch (choice.kind) {
    case 'item': {
      const name = gearRealName(choice.item).trim();
      if (!name) return null;
      return {
        item_id: choice.item.id,
        ...(choice.item.catalog_id ? { catalog_id: choice.item.catalog_id } : {}),
        name,
      };
    }
    case 'catalog':
      return { catalog_id: choice.catalog.id, name: choice.catalog.name };
    case 'text': {
      const name = choice.text.trim();
      return name ? { name } : null;
    }
    case 'snapshot':
      return { ...choice.entry };
  }
}

export type BuiltGear = {
  gear: GearSnapshot;
  brewer_catalog_id: string | null;
  grinder_catalog_id: string | null;
};

/** The `gear` snapshot and the two filter columns for a version, from the picker choices. */
export function buildGear(selection: GearSelection): BuiltGear {
  const gear: GearSnapshot = {};
  for (const category of RECIPE_GEAR_CATEGORIES) {
    const choice = selection[category];
    const entry = choice ? choiceToEntry(choice) : null;
    if (entry) gear[category] = entry;
  }
  return {
    gear,
    brewer_catalog_id: gear.brewer?.catalog_id ?? null,
    grinder_catalog_id: gear.grinder?.catalog_id ?? null,
  };
}

/** A new recipe starts with my default item in each category (nothing where I have no default). */
export function defaultGearSelection(items: readonly GearItem[]): GearSelection {
  const selection: GearSelection = {};
  for (const category of RECIPE_GEAR_CATEGORIES) {
    const item = items.find((i) => i.category === category && i.is_default);
    if (item) selection[category] = { kind: 'item', item };
  }
  return selection;
}

/**
 * A new version (or an edit) starts from the version's own snapshot, never from today's defaults.
 * Entries are kept exactly as saved, so renaming or deleting gear later changes nothing.
 */
export function selectionFromSnapshot(snapshot: GearSnapshot | null | undefined): GearSelection {
  const selection: GearSelection = {};
  for (const category of RECIPE_GEAR_CATEGORIES) {
    const entry = snapshot?.[category];
    if (entry) selection[category] = { kind: 'snapshot', entry };
  }
  return selection;
}

/** My gear first (defaults marked and listed first), grouped for one category's picker. */
export function gearPickerOrder<T extends Pick<GearItem, 'category' | 'is_default'>>(
  items: readonly T[],
  category: GearCategory,
): T[] {
  return items
    .filter((i) => i.category === category)
    .sort((a, b) => Number(b.is_default) - Number(a.is_default));
}

/** Matches typed text against a catalogue entry's brand and model, ignoring case and spacing. */
export function catalogMatches(
  entry: Pick<CatalogEntry, 'brand' | 'model'>,
  query: string,
): boolean {
  const words = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (words.length === 0) return true;
  const haystack = `${entry.brand} ${entry.model}`.toLowerCase();
  return words.every((w) => haystack.includes(w));
}
